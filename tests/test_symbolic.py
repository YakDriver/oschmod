@pytest.mark.parametrize(("start", "mode", "file_result", "dir_result"), GNU_CHMOD)
def test_matches_gnu_chmod(start, mode, file_result, dir_result):
    assert oschmod.get_effective_mode(start, mode) == file_result
    assert oschmod.get_effective_mode(start, mode, is_dir=True) == dir_result


@pytest.mark.parametrize(
    "bad",
    ["g=ux", "u=gu", "u+z", "ug", "u=,", ",", "u+x,", "", "u+x y", "u+r,g=", "+X+"],
)
def test_invalid_syntax(bad):
    if bad in ("u+r,g=", "+X+"):  # valid in GNU chmod
        oschmod.get_effective_mode(0o644, bad)
        return
    with pytest.raises(oschmod.ModeError):
        oschmod.get_effective_mode(0o644, bad)


def test_x_uses_mode_after_earlier_actions():
    # GNU evaluates X against the mode built so far, so u-x,a+X on 0o744 adds nothing.
    assert oschmod.get_effective_mode(0o744, "u-x,a+X") == 0o644
    assert oschmod.get_effective_mode(0o744, "u-x,a+X", is_dir=True) == 0o755


def test_whitespace_around_clauses_is_allowed():
    """Earlier versions accepted it, so keep accepting it."""
    assert oschmod.get_effective_mode(0o600, " u+x , g+r ") == 0o740


@pytest.mark.skipif(sys.platform == "win32", reason="POSIX special bits")
@pytest.mark.parametrize(
    ("start", "mode", "file_result", "dir_result"),
    [row for row in GNU_CHMOD if row[0] in (0o0644, 0o2750, 0o1777)],
)
def test_set_mode_matches_gnu_chmod(tmp_path, start, mode, file_result, dir_result):
    """The same table through set_mode, where is_dir comes from the filesystem."""
    file_path = tmp_path / "f"
    file_path.write_text("x")
    dir_path = tmp_path / "d"
    dir_path.mkdir()
    try:
        for path, expected in ((file_path, file_result), (dir_path, dir_result)):
            os.chmod(path, start)
            oschmod.set_mode(path, mode)
            assert oschmod.get_full_mode(path) == expected, path.name
    finally:
        os.chmod(dir_path, 0o700)
